#!/usr/bin/env python3
"""Remove the Direct inbox Requests navigation and Compose header action (Instagram 454).

Keep the Messages title and inbox contents intact. Fail closed if upstream
Smali changes, and validate every class before writing any patched classes.
"""
from __future__ import annotations

import argparse
import re
from pathlib import Path


class PatchMismatch(Exception):
    pass


METHOD_RE = re.compile(r"(?ms)^\.method public final A06\(\)V\n.*?^\.end method$")
REQUEST_TITLE = "    const v7, 0x7f133e2b"
REQUEST_MODE = "    sget-object v14, LX/01tK;->A00:LX/01tK;"
REQUEST_CONSTRUCTOR = (
    "    invoke-direct/range {v12 .. v22}, LX/0X7V;-><init>"
    "(LX/0RDO;LX/06Zx;Ljava/lang/Integer;Ljava/lang/Integer;"
    "Ljava/lang/Integer;Ljava/lang/Integer;Ljava/util/Set;ZZZ)V"
)
REQUEST_ADD = (
    "    invoke-virtual {v0, v12}, "
    "Ljava/util/AbstractCollection;->add(Ljava/lang/Object;)Z\n"
)
LIST_COMMIT = "    new-instance v5, LX/05Ku;"

PRIMARY_CLASS = ".class public final LX/0RDL;"
PRIMARY_METHOD_RE = re.compile(
    r"(?ms)^\.method public final A01\(Lcom/instagram/common/session/UserSession;"
    r"LX/06Zx;LX/0Jnp;IZZZ\)LX/05Ku;\n.*?^\.end method$"
)
PRIMARY_REQUEST_MODE = "    sget-object v6, LX/01tK;->A00:LX/01tK;"
PRIMARY_CONSTRUCTOR = (
    "    invoke-direct/range {v21 .. v31}, LX/0X7V;-><init>"
    "(LX/0RDO;LX/06Zx;Ljava/lang/Integer;Ljava/lang/Integer;"
    "Ljava/lang/Integer;Ljava/lang/Integer;Ljava/util/Set;ZZZ)V"
)
PRIMARY_ADD = (
    "    invoke-virtual {v7, v1}, "
    "Ljava/util/AbstractCollection;->add(Ljava/lang/Object;)Z\n"
)
PRIMARY_SKIP = """    iget-object v2, v4, Landroid/util/Pair;->second:Ljava/lang/Object;

    sget-object v3, LX/01tK;->A00:LX/01tK;

    invoke-static {v2, v3}, LX/00d6;->areEqual(Ljava/lang/Object;Ljava/lang/Object;)Z

    move-result v2

    if-nez v2, :goto_4

"""

# Instagram 454 uses a full-screen Compose inbox. The Requests action beside
# "Messages" is generated by DefaultHeader (InboxHeader.kt), *not* by the
# legacy RecyclerView. Omitting the Text composable call also removes its
# click target and accessibility semantics, without touching the title.
COMPOSE_HEADER_CLASS = ".class public abstract LX/0ZY5;"
COMPOSE_HEADER_METHOD_RE = re.compile(
    r"(?ms)^\.method public static final A01\(LX/1BaO;LX/05KL;"
    r"Lkotlin/jvm/functions/Function0;Lkotlin/jvm/functions/Function0;I\)V\n"
    r".*?^\.end method$"
)
COMPOSE_HEADER_ACTION = (
    "    move-object v10, v7\n\n"
    "    move-object v13, v2\n\n"
    "    move-wide/from16 v14, v19\n\n"
    "    invoke-static/range {v10 .. v15}, LX/04cX;"
    "->A1T(LX/1BaO;LX/05n4;LX/04cD;Ljava/lang/String;J)V\n"
)
COMPOSE_HEADER_ACTION_SKIP = COMPOSE_HEADER_ACTION.replace(
    "    invoke-static/range {v10 .. v15}, LX/04cX;"
    "->A1T(LX/1BaO;LX/05n4;LX/04cD;Ljava/lang/String;J)V\n",
    "",
)


def _one_method(source: str, class_marker: str, method_re: re.Pattern, name: str):
    if class_marker not in source:
        raise PatchMismatch(f"{name} class changed")
    matches = list(method_re.finditer(source))
    if len(matches) != 1:
        raise PatchMismatch(f"expected one {name} method, found {len(matches)}")
    return matches[0], matches[0].group()


def transform(source: str) -> str:
    match, method = _one_method(
        source, ".class public final LX/05PM;", METHOD_RE, "legacy navigation"
    )
    for marker in (REQUEST_TITLE, REQUEST_MODE, REQUEST_CONSTRUCTOR, LIST_COMMIT):
        if method.count(marker) != 1:
            raise PatchMismatch(f"legacy Requests fingerprint changed: {marker}")
    positions = [
        method.index(REQUEST_TITLE),
        method.index(REQUEST_MODE),
        method.index(REQUEST_CONSTRUCTOR),
        *[m.start() for m in re.finditer(re.escape(REQUEST_ADD), method)],
        method.index(LIST_COMMIT),
    ]
    if len(positions) != 5 or positions != sorted(positions):
        raise PatchMismatch("legacy Requests insertion changed")
    updated = method.replace(REQUEST_ADD, "", 1)
    return source[:match.start()] + updated + source[match.end():]


def transform_primary(source: str) -> str:
    match, method = _one_method(
        source, PRIMARY_CLASS, PRIMARY_METHOD_RE, "primary navigation"
    )
    for marker in (PRIMARY_REQUEST_MODE, PRIMARY_CONSTRUCTOR, PRIMARY_ADD):
        if method.count(marker) != 1:
            raise PatchMismatch(f"primary Requests fingerprint changed: {marker}")
    mode = method.index(PRIMARY_REQUEST_MODE)
    constructor = method.index(PRIMARY_CONSTRUCTOR)
    addition = method.index(PRIMARY_ADD)
    if not (mode < constructor < addition < method.index("    goto/16 :goto_4", addition)):
        raise PatchMismatch("primary Requests insertion changed")
    updated = method.replace(PRIMARY_ADD, PRIMARY_SKIP + PRIMARY_ADD, 1)
    return source[:match.start()] + updated + source[match.end():]


def transform_compose_header(source: str) -> str:
    match, method = _one_method(
        source, COMPOSE_HEADER_CLASS, COMPOSE_HEADER_METHOD_RE, "Compose DefaultHeader"
    )
    for marker in (
        "instagram.features.direct.inbox.feature.inboxheader.ui.DefaultHeader",
        '    const-string v0, "header_action_button"',
        "    iget-object v2, v6, LX/05KL;->A02:Ljava/lang/String;",
        COMPOSE_HEADER_ACTION,
    ):
        if method.count(marker) != 1:
            raise PatchMismatch(f"Compose Requests action changed: {marker}")
    updated = method.replace(COMPOSE_HEADER_ACTION, COMPOSE_HEADER_ACTION_SKIP, 1)
    return source[:match.start()] + updated + source[match.end():]


def patch(root: Path, *, check: bool = False) -> Path:
    if not root.is_dir():
        raise PatchMismatch(f"decoded APK missing: {root}")
    paths = []
    for filename in ("05PM.smali", "0RDL.smali", "0ZY5.smali"):
        matches = list(root.rglob(filename))
        if len(matches) != 1:
            raise PatchMismatch(f"expected one {filename}, found {len(matches)}")
        paths.append(matches[0])
    transforms = (transform, transform_primary, transform_compose_header)
    # All-or-nothing validation: never partially patch an incompatible APK.
    updates = [(path, fn(path.read_text())) for path, fn in zip(paths, transforms)]
    if not check:
        for path, updated in updates:
            path.write_text(updated)
    return paths[2]


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("decoded_apk", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        patch(args.decoded_apk, check=args.check)
    except PatchMismatch as exc:
        parser.exit(1, f"ERROR: Message Requests link patch incompatible: {exc}\n")
    print("GramForge Message Requests link " + ("verified" if args.check else "hidden"))

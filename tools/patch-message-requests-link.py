def _one_method(source: str, class_marker: str, method_re: re.Pattern, name: str):
    if class_marker not in source:
        raise PatchMismatch(f"{name} class changed")
    matches = list(method_re.finditer(source))
    if len(matches) != 1:
        raise PatchMismatch(f"expected one {name} method, found {len(matches)}")
    return matches[0], matches[0].group()


def transform(source: str) -> str:
    match, method = _one_method(
        source, ".class public final LX/05PM;", METHOD_RE, "legacy navigation"
    )
    for marker in (REQUEST_TITLE, REQUEST_MODE, REQUEST_CONSTRUCTOR, LIST_COMMIT):
        if method.count(marker) != 1:
            raise PatchMismatch(f"legacy Requests fingerprint changed: {marker}")
    positions = [
        method.index(REQUEST_TITLE),
        method.index(REQUEST_MODE),
        method.index(REQUEST_CONSTRUCTOR),
        *[m.start() for m in re.finditer(re.escape(REQUEST_ADD), method)],
        method.index(LIST_COMMIT),
    ]
    if len(positions) != 5 or positions != sorted(positions):
        raise PatchMismatch("legacy Requests insertion changed")
    updated = method.replace(REQUEST_ADD, "", 1)
    return source[:match.start()] + updated + source[match.end():]


def transform_primary(source: str) -> str:
    match, method = _one_method(
        source, PRIMARY_CLASS, PRIMARY_METHOD_RE, "primary navigation"
    )
    for marker in (PRIMARY_REQUEST_MODE, PRIMARY_CONSTRUCTOR, PRIMARY_ADD):
        if method.count(marker) != 1:
            raise PatchMismatch(f"primary Requests fingerprint changed: {marker}")
    mode = method.index(PRIMARY_REQUEST_MODE)
    constructor = method.index(PRIMARY_CONSTRUCTOR)
    addition = method.index(PRIMARY_ADD)
    if not (mode < constructor < addition < method.index("    goto/16 :goto_4", addition)):
        raise PatchMismatch("primary Requests insertion changed")
    updated = method.replace(PRIMARY_ADD, PRIMARY_SKIP + PRIMARY_ADD, 1)
    return source[:match.start()] + updated + source[match.end():]


